// Take two variables price1 and price2, and compare them using all comparison operators (==, ===, !=, !==, >, <, >=, <=), printing each result with console.log.


const price1 = 100;
const price2 = 200;

console.log(price1 == price2); // false
console.log(price1 === price2); // false
console.log(price1 != price2); // true
console.log(price1 !== price2); // true
console.log(price1 > price2); // false
console.log(price1 < price2); // true
console.log(price1 >= price2); // false
console.log(price1 <= price2); // true
